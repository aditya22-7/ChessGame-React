CREATE TABLE game_session (
  game_session_id VARCHAR(36) PRIMARY KEY,
  origin VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tournament_match_id VARCHAR(36) NULL,
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'WAITING',
  engine_ruleset_version VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  current_move_sequence INT UNSIGNED NOT NULL DEFAULT 0,
  state_snapshot_json JSON NULL,
  snapshot_move_sequence INT UNSIGNED NOT NULL DEFAULT 0,
  snapshot_checksum CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  side_to_move VARCHAR(5) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'WHITE',
  draw_offer_participant_id VARCHAR(36) NULL,
  draw_offered_at DATETIME(3) NULL,
  started_at DATETIME(3) NULL,
  finished_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  lock_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
  UNIQUE KEY uq_session_match (tournament_match_id),
  UNIQUE KEY uq_session_match_scope (game_session_id, tournament_match_id),
  UNIQUE KEY uq_session_origin (game_session_id, origin),
  UNIQUE KEY uq_session_result_scope (game_session_id, origin, tournament_match_id),
  KEY ix_session_recovery (status, started_at),
  CONSTRAINT fk_session_match FOREIGN KEY (tournament_match_id) REFERENCES tournament_match (match_id),
  CONSTRAINT ck_session_origin CHECK ((origin = 'QUICK_PLAY' AND tournament_match_id IS NULL) OR (origin = 'TOURNAMENT' AND tournament_match_id IS NOT NULL)),
  CONSTRAINT ck_session_state CHECK (status IN ('WAITING','IN_PROGRESS','FINALIZED')),
  CONSTRAINT ck_session_started CHECK (status <> 'IN_PROGRESS' OR started_at IS NOT NULL),
  CONSTRAINT ck_session_finished CHECK ((status = 'FINALIZED' AND finished_at IS NOT NULL) OR (status <> 'FINALIZED' AND finished_at IS NULL)),
  CONSTRAINT ck_session_snapshot CHECK (snapshot_move_sequence <= current_move_sequence AND (state_snapshot_json IS NOT NULL OR snapshot_move_sequence = 0)),
  CONSTRAINT ck_session_snapshot_object CHECK (state_snapshot_json IS NULL OR JSON_TYPE(state_snapshot_json) = 'OBJECT'),
  CONSTRAINT ck_session_turn CHECK (side_to_move IN ('WHITE','BLACK')),
  CONSTRAINT ck_session_offer_time CHECK ((draw_offer_participant_id IS NULL AND draw_offered_at IS NULL) OR (draw_offer_participant_id IS NOT NULL AND draw_offered_at IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

