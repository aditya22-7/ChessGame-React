CREATE TABLE game_result (
  result_id VARCHAR(36) PRIMARY KEY,
  context VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tournament_match_id VARCHAR(36) NULL,
  game_session_id VARCHAR(36) NULL,
  outcome VARCHAR(9) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  reason VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  white_points DECIMAL(4,2) NOT NULL,
  black_points DECIMAL(4,2) NOT NULL,
  effective_at DATETIME(3) NOT NULL,
  recorded_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  rules_version VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  UNIQUE KEY uq_result_match (tournament_match_id),
  UNIQUE KEY uq_result_session (game_session_id),
  UNIQUE KEY uq_result_session_identity (result_id, game_session_id),
  CONSTRAINT fk_result_match FOREIGN KEY (tournament_match_id) REFERENCES tournament_match (match_id),
  CONSTRAINT fk_result_session FOREIGN KEY (game_session_id) REFERENCES game_session (game_session_id),
  CONSTRAINT fk_result_origin FOREIGN KEY (game_session_id, context) REFERENCES game_session (game_session_id, origin),
  CONSTRAINT fk_result_session_match FOREIGN KEY (game_session_id, context, tournament_match_id) REFERENCES game_session (game_session_id, origin, tournament_match_id),
  CONSTRAINT ck_result_context CHECK ((context = 'QUICK_PLAY' AND game_session_id IS NOT NULL AND tournament_match_id IS NULL) OR (context = 'TOURNAMENT' AND tournament_match_id IS NOT NULL)),
  CONSTRAINT ck_result_score CHECK ((outcome = 'WHITE_WIN' AND white_points = 1 AND black_points = 0) OR (outcome = 'BLACK_WIN' AND white_points = 0 AND black_points = 1) OR (outcome = 'DRAW' AND white_points = 0.5 AND black_points = 0.5)),
  CONSTRAINT ck_result_reason CHECK (reason IN ('GAME_COMPLETED','RESIGNATION','DRAW_AGREEMENT','MATCH_DEADLINE','SINGLE_NO_SHOW','DOUBLE_NO_SHOW','WITHDRAWAL','RECONNECT_EXPIRED','DOUBLE_DISCONNECT')),
  CONSTRAINT ck_result_draw_reason CHECK (reason NOT IN ('DRAW_AGREEMENT','MATCH_DEADLINE','DOUBLE_NO_SHOW','DOUBLE_DISCONNECT') OR outcome = 'DRAW'),
  CONSTRAINT ck_result_decisive_reason CHECK (reason NOT IN ('RESIGNATION','SINGLE_NO_SHOW','WITHDRAWAL','RECONNECT_EXPIRED') OR outcome IN ('WHITE_WIN','BLACK_WIN')),
  CONSTRAINT ck_result_recorded CHECK (recorded_at >= effective_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

