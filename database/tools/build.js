const fs = require('node:fs');
const path = require('node:path');
const { root, migrations } = require('./sql');
const { journalDDL } = require('./journal');
const content = '-- GENERATED by npm --prefix database run build. Edit migrations, not this file.\n' +
  '-- Fresh databases only. Select an EMPTY schema in the mysql client first.\n' +
  '-- For tracked deployment and existing databases, use tools/migrate.js instead.\n' +
  "SET NAMES utf8mb4 COLLATE utf8mb4_0900_ai_ci;\nSET time_zone = '+00:00';\nSET SESSION sql_mode = 'STRICT_TRANS_TABLES,NO_ZERO_DATE,NO_ZERO_IN_DATE,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION';\n" +
  journalDDL.replace('CREATE TABLE IF NOT EXISTS','CREATE TABLE')+';\n'+
  migrations().map(m=>'\n-- Migration '+m.name+'\n'+
    `INSERT INTO schema_migration(version,filename,checksum,status) VALUES ('${m.version}','${m.name}','${m.checksum}','RUNNING');\n`+
    m.sql.replace(/\r\n/g,'\n')+`\nUPDATE schema_migration SET status='APPLIED',finished_at=UTC_TIMESTAMP(3) WHERE version='${m.version}';\n`).join('\n');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(path.join(root,'schema.sql')) || fs.readFileSync(path.join(root,'schema.sql'),'utf8').replace(/\r\n/g,'\n')!==content) throw new Error('schema.sql differs from migrations; rebuild it');
} else { fs.writeFileSync(path.join(root,'schema.sql'),content); console.log('Built database/schema.sql'); }
